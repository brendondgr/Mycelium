"""EXP-2026-11-010 A7 and A8 (Amendment 10): the rows after the fixes beside A6's, from
data/metrics.json (analyse.py) and the A7 run files. Standard library only.

    python3 docs/research/experiments/EXP-2026-11-010-agent-loop-cost/code/a7_table.py

Writes data/metrics_a7.json and tables/a7.md. Seconds are printed but A6 ran on
a server with nothing else on it and A7 on one shared with the operator's own
work (Amendment 9), so only calls and tokens per turn are comparable.
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
RUNS = [("a6idle", "before the fixes, second server"), ("a7idle", "after the fixes, shared server"),
        ("a8idle", "after the afternoon's fixes, shared server"),
        ("a6p8", "before the fixes, second server"), ("a7p8", "after the fixes, shared server"),
        ("a8p8", "after the afternoon's fixes, shared server")]
GROUPS = ("single", "few", "compound")


def rows(tag):
    p = HERE / "data" / f"a2_{tag}.jsonl"
    return [json.loads(x) for x in p.open()] if p.exists() else []


def main() -> int:
    m = json.loads((HERE / "data" / "metrics.json").read_text())["a2"]
    out = {"runs": {}, "per_group": {}, "a7": {}}
    lines = ["<!-- generated by code/a7_table.py; do not edit -->", "",
             "| Run | In flight | Group | Turns | Function calls (median/max) | Model calls (median/max) | Median tokens | Median s | Worst s |",
             "|---|---:|---|---:|---|---|---:|---:|---:|"]
    for tag, label in RUNS:
        v = m.get(tag)
        if not v:
            continue
        rs = rows(tag)
        out["runs"][tag] = {"label": label, "in_flight": v["in_flight"], "errors": v["errors"],
                            "groups": {g: v[g] for g in GROUPS}}
        for g in GROUPS:
            s = v[g]
            fc = [r["function_calls"] for r in rs if r.get("group") == g and "function_calls" in r]
            fcs = f"{statistics.median(fc):g}/{max(fc)}" if fc else "—"
            out["per_group"].setdefault(g, {})[tag] = {
                "turns": s["n"], "function_calls_median": statistics.median(fc) if fc else None,
                "function_calls_max": max(fc) if fc else None,
                "model_calls_median": s["model_calls_median"], "model_calls_max": s["model_calls_max"],
                "tokens_median": s["tokens_median"], "wall_s_median": s["wall_s_median"], "wall_s_max": s["wall_s_max"]}
            lines.append(f"| {tag} ({label}) | {v['in_flight']} | {g} | {s['n']} | {fcs} | "
                         f"{s['model_calls_median']:g}/{s['model_calls_max']} | {s['tokens_median'] / 1000:.1f}k | "
                         f"{s['wall_s_median']} | {s['wall_s_max']} |")
    lines += ["", "| Run | Turns | With text | Turn errors (codes) | Hit the step limit | Function results (ok) | Calls denied | Turns with a denied call | Empty model calls | Calls at the reply cap |",
              "|---|---:|---:|---|---:|---:|---:|---:|---:|---:|"]
    for tag in ("a6idle", "a6p8", "a7idle", "a7p8", "a8idle", "a8p8"):
        rs = rows(tag)
        if not rs:
            continue
        codes = sorted(str((e or {}).get("code") if isinstance(e, dict) else e)
                       for r in rs for e in (r.get("errors") or []))
        status = [x.get("status") for r in rs for x in (r.get("results") or []) if isinstance(x, dict)]
        a = {"turns": len(rs),
             "turns_with_text": sum(1 for r in rs if (r.get("final_text") or "").strip()),
             "turn_error_codes": {c: codes.count(c) for c in dict.fromkeys(codes)},
             "hit_max_steps": sum(bool(r.get("hit_max_steps")) for r in rs),
             # A row's `results` holds the results that came back ok; the
             # denied ones are counted in its `denied` field.
             "function_results_ok": status.count("ok"),
             "denied": sum(int(r.get("denied") or 0) for r in rs),
             "turns_with_denied": sum(1 for r in rs if r.get("denied")),
             "empty_calls": sum(r.get("empty_calls") or 0 for r in rs),
             "cap_hits": sum(r.get("cap_hits") or 0 for r in rs)}
        out["a7"][tag] = a
        shown = ", ".join(f"{c} {n}" for c, n in a["turn_error_codes"].items()) or "none"
        lines.append(f"| {tag} | {a['turns']} | {a['turns_with_text']} | {shown} | {a['hit_max_steps']} | "
                     f"{a['function_results_ok']} | {a['denied']} | {a['turns_with_denied']} | {a['empty_calls']} | {a['cap_hits']} |")
    (HERE / "data" / "metrics_a7.json").write_text(json.dumps(out, indent=1) + "\n")
    (HERE / "tables" / "a7.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
