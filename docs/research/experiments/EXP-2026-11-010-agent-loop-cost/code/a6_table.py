"""EXP-2026-11-010 Amendments 6-8 (round three, arm A6): the A6 rows beside
round one's (A2/A3, Qwen 3.8 27B, 2026-11-12/13) and round two's (A5, Gemma 4
31B), read from ``data/metrics.json`` (run ``code/analyse.py`` first), plus the
reply-cap and thinking-budget counts ``run_a6.py`` stored per turn. Writes
``tables/a6.md`` and ``data/metrics_a6.json``.

    python3 docs/research/experiments/EXP-2026-11-010-agent-loop-cost/code/a6_table.py
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
RUNS = [("a2idle", "round one, Qwen 3.8 27B"), ("a5idle", "round two, Gemma 4 31B"), ("a6idle", "round three, Qwen 3.8 27B"),
        ("a3p8", "round one"), ("a5p8", "round two"), ("a6p8", "round three"), ("a6x64", "round three")]


def main() -> int:
    m = json.loads((HERE / "data" / "metrics.json").read_text())["a2"]
    lines = ["<!-- generated by code/a6_table.py from data/metrics.json; do not edit -->", "",
             "| Run | In flight | Group | Turns | Median s | Worst s | Median tokens | Model calls (median/max) |",
             "|---|---:|---|---:|---:|---:|---:|---|"]
    out = {"runs": {}, "a6": {}}
    for tag, label in RUNS:
        v = m.get(tag)
        if not v:
            continue
        for g in ("single", "few", "compound"):
            s = v[g]
            lines.append(f"| {tag} ({label}) | {v['in_flight']} | {g} | {s['n']} | {s['wall_s_median']} | {s['wall_s_max']} | "
                         f"{s['tokens_median'] / 1000:.1f}k | {s['model_calls_median']:g}/{s['model_calls_max']} |")
        u5 = v["turns_with_up_to_5_function_calls"]
        out["runs"][tag] = {"in_flight": v["in_flight"], "groups": {g: v[g] for g in ("single", "few", "compound")},
                            "up_to_5_calls": u5, "model_call_latency_s": v["model_call_latency_s"],
                            "batch_wall_s": v["batch_wall_s"], "errors": v["errors"]}
    lines += ["", "| Run | Turns of ≤ 5 function calls | Their worst s | Their worst tokens | Model-call latency median / p90 s | Batch wall s (median) | Errors |",
              "|---|---:|---:|---:|---|---:|---:|"]
    for tag, _ in RUNS:
        r = out["runs"].get(tag)
        if not r:
            continue
        u5, lat = r["up_to_5_calls"], r["model_call_latency_s"]
        lines.append(f"| {tag} | {u5.get('n')} | {u5.get('wall_s_max')} | {u5.get('tokens_max')} | "
                     f"{lat.get('median')} / {lat.get('p90')} | {r['batch_wall_s']['median']} | {r['errors']} |")
    lines += ["", "Reply cap and thinking budget (A6 only; `run_a6.py`):", "",
              "| Run | Turns | Model calls | Calls at the reply cap | Calls at the thinking budget | Reasoning tokens reported | Empty calls | Turns with text |",
              "|---|---:|---:|---:|---:|---|---:|---:|"]
    for tag in ("a6idle", "a6p8", "a6x64"):
        rows = [json.loads(x) for x in (HERE / "data" / f"a2_{tag}.jsonl").open()]
        calls = [c for r in rows for c in (r.get("model_call_log") or [])]
        rep = [c.get("reasoning_tokens") for c in calls if c.get("reasoning_tokens") is not None]
        a = {"turns": len(rows), "model_calls": len(calls),
             "cap_hits": sum(r.get("cap_hits") or 0 for r in rows),
             "thinking_budget_hits": (sum(r.get("thinking_budget_hits") or 0 for r in rows)
                                      if any(r.get("thinking_budget_hits") is not None for r in rows) else None),
             "reasoning_tokens_reported": len(rep),
             "reasoning_tokens_median": statistics.median(rep) if rep else None,
             "empty_calls": sum(r.get("empty_calls") or 0 for r in rows),
             "turns_with_text": sum(1 for r in rows if (r.get("final_text") or "").strip()),
             "max_output_tokens": rows[0].get("max_output_tokens"), "thinking_budget": rows[0].get("thinking_budget")}
        out["a6"][tag] = a
        lines.append(f"| {tag} | {a['turns']} | {a['model_calls']} | {a['cap_hits']} | "
                     f"{'not reported' if a['thinking_budget_hits'] is None else a['thinking_budget_hits']} | "
                     f"{a['reasoning_tokens_reported']} of {a['model_calls']} | {a['empty_calls']} | {a['turns_with_text']} |")
    lines.append("")
    lines.append(f"Reply cap `max_output_tokens` = {out['a6']['a6idle']['max_output_tokens']}, "
                 f"`thinking_budget` = {out['a6']['a6idle']['thinking_budget']}.")
    (HERE / "data" / "metrics_a6.json").write_text(json.dumps(out, indent=1) + "\n")
    (HERE / "tables" / "a6.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
