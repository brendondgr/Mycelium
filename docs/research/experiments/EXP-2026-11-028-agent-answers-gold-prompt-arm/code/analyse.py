"""EXP-2026-11-028: the registered metrics (PROTOCOL.md, Metrics) from the
collected files. Standard library only; run from anywhere.

    python3 docs/research/experiments/EXP-2026-11-028-agent-answers-gold-prompt-arm/code/analyse.py

Reads, under ``data/raw/EXP-2026-11-018-agent-answers-gold/data/``:
``graded_<tag>.jsonl`` (EXP-2026-11-018's ``r4.py grade``, unchanged: one row
per job with its primary and secondary grade) and the two arms' raw rows
``runs_<tag>_code.jsonl`` and ``runs_<tag>_prompt.jsonl``. Writes
``data/metrics.json``, ``data/metrics.csv``, ``tables/summary.md`` and the
``metrics.values`` block of ``manifest.yaml``. Smoke rows (tag ``smoke``) are
never read.
"""

from __future__ import annotations

import csv
import gzip
import json
import random
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
RAW = HERE / "data" / "raw" / "EXP-2026-11-018-agent-answers-gold" / "data"
#: (model as the operator states it, key in metric names, tag)
MODELS = [("Gemma 4 31B", "gemma", "s28"), ("Qwen 3.8 27B", "qwen", "q28"),
          ("Inkling 2 Mini", "inkling", "i28")]
ARMS = ("code", "prompt")
ANSWERABLE = ("field", "list", "project", "people", "join")
KINDS = ANSWERABLE + ("unanswerable",)
SEED, BOOT = 20261115, 10000


def jsonl(path: Path) -> list[dict]:
    if not path.exists() and path.with_name(path.name + ".gz").exists():
        path = path.with_name(path.name + ".gz")
    if not path.exists():
        return []
    raw = gzip.decompress(path.read_bytes()).decode() if path.suffix == ".gz" else path.read_text()
    return [json.loads(x) for x in raw.splitlines() if x.strip()]


def boot(vals: list[float]) -> list:
    """Bootstrap 95% interval of the mean over questions (as EXP-2026-11-018's
    ``grade.boot_mean``: 10,000 resamples, seed 20261115)."""
    rng = random.Random(SEED)
    n = len(vals)
    if not n:
        return [None, None]
    means = sorted(sum(vals[rng.randrange(n)] for _ in range(n)) / n for _ in range(BOOT))
    return [round(means[int(0.025 * BOOT)], 4), round(means[int(0.975 * BOOT) - 1], 4)]


def main() -> int:
    out, flat, manifest = {}, [], {}
    lines = ["<!-- generated by code/analyse.py; do not edit -->"]
    for name, key, tag in MODELS:
        graded = jsonl(RAW / f"graded_{tag}.jsonl")
        if not graded:
            continue
        kind_of = {g["id"]: g["kind"] for g in graded}
        res = {"model": name, "tag": tag, "questions": len(kind_of), "arms": {}, "differences": {}}

        def per_q(arm, grading, field="full"):
            by = {}
            for g in graded:
                if g["arm"] == arm and field in g[grading]:
                    by.setdefault(g["id"], []).append(g[grading][field])
            return {q: statistics.mean(v) for q, v in by.items()}

        for arm in ARMS:
            runs = [g for g in graded if g["arm"] == arm]
            raw = jsonl(RAW / f"runs_{tag}_{arm}.jsonl")
            first = [r for r in raw if r.get("attempt", 1) == 1]
            e = {"jobs": len(runs), "failed_jobs_after_retry": sum(bool(g["failed"]) for g in runs),
                 "failed_first_attempts": sum(bool(r.get("failed")) for r in first),
                 "failed_first_attempts_by_reason": {
                     why: sum(1 for r in first if r.get("failed") == why)
                     for why in sorted({r["failed"] for r in first if r.get("failed")})},
                 "attempts": len(raw),
                 "attempts_with_policy_in_prompt": sum(bool(r.get("policy_in_prompt")) for r in raw),
                 "attempts_with_prompt_seen": sum(r.get("policy_in_prompt") is not None for r in raw),
                 "calls_gate_did_not_allow": sum(r.get("gate_would_not_allow") or 0 for r in raw),
                 "attempts_with_a_call_gate_did_not_allow": sum(bool(r.get("gate_would_not_allow")) for r in raw),
                 "calls_denied_in_the_turn": sum(r.get("denied") or 0 for r in raw),
                 "function_calls": sum(r.get("function_calls") or 0 for r in raw),
                 "gate_errors": sum(r.get("gate_errors") or 0 for r in raw),
                 "wall_s_median": round(statistics.median([r["wall_s"] for r in raw if r.get("wall_s")]), 2)
                 if any(r.get("wall_s") for r in raw) else None}
            for grading in ("primary", "secondary"):
                ans = [g for g in runs if g["kind"] in ANSWERABLE]
                k = sum(g[grading]["full"] for g in ans)
                fq = per_q(arm, grading)
                e[grading] = {"answerable_full": {"k": k, "n": len(ans), "rate": round(k / len(ans), 4) if ans else None,
                                                  "boot95_questions": boot([fq[q] for q in fq if kind_of[q] in ANSWERABLE])},
                              "by_kind": {}}
                for kind in KINDS:
                    kr = [g for g in runs if g["kind"] == kind]
                    if kr:
                        kk = sum(g[grading]["full"] for g in kr)
                        e[grading]["by_kind"][kind] = {"k": kk, "n": len(kr)}
                        flat.append({"model": name, "arm": arm, "grading": grading, "kind": kind,
                                     "metric": "full_credit", "k": kk, "n": len(kr), "value": round(kk / len(kr), 4),
                                     "lo": "", "hi": ""})
                un = [g for g in runs if g["kind"] == "unanswerable"]
                sf = sum(g[grading].get("states_fact", 0) for g in un)
                e[grading]["unanswerable_states_fact"] = {"k": sf, "n": len(un)}
                flat.append({"model": name, "arm": arm, "grading": grading, "kind": "answerable",
                             "metric": "full_credit", "k": k, "n": len(ans),
                             "value": e[grading]["answerable_full"]["rate"],
                             "lo": e[grading]["answerable_full"]["boot95_questions"][0],
                             "hi": e[grading]["answerable_full"]["boot95_questions"][1]})
                flat.append({"model": name, "arm": arm, "grading": grading, "kind": "unanswerable",
                             "metric": "states_fact", "k": sf, "n": len(un),
                             "value": round(sf / len(un), 4) if un else None, "lo": "", "hi": ""})
                if grading == "primary":
                    manifest[f"{key}.{arm}.answerable_full"] = (k, len(ans))
                    manifest[f"{key}.{arm}.unanswerable_states_fact"] = (sf, len(un))
            manifest[f"{key}.{arm}.failed_jobs_after_retry"] = (e["failed_jobs_after_retry"], e["jobs"])
            manifest[f"{key}.{arm}.calls_denied_in_the_turn"] = (e["calls_denied_in_the_turn"], e["function_calls"])
            res["arms"][arm] = e

        for grading in ("primary", "secondary"):
            fa, fb = per_q("code", grading), per_q("prompt", grading)
            d = {}
            for label, subset in [("answerable", ANSWERABLE), ("all", KINDS), *[(k, (k,)) for k in KINDS]]:
                common = [q for q in fa if q in fb and kind_of[q] in subset]
                diffs = [fa[q] - fb[q] for q in common]
                if not diffs:
                    continue
                d[label] = {"diff": round(statistics.mean(diffs), 4), "boot95": boot(diffs),
                            "n_questions": len(common),
                            "code": round(statistics.mean(fa[q] for q in common), 4),
                            "prompt": round(statistics.mean(fb[q] for q in common), 4),
                            "questions_code_higher": sum(x > 0 for x in diffs),
                            "questions_prompt_higher": sum(x < 0 for x in diffs)}
                flat.append({"model": name, "arm": "code_minus_prompt", "grading": grading, "kind": label,
                             "metric": "paired_diff_full", "k": "", "n": len(common), "value": d[label]["diff"],
                             "lo": d[label]["boot95"][0], "hi": d[label]["boot95"][1]})
            res["differences"][grading] = d
        p = res["differences"]["primary"].get("answerable")
        if p:
            res["claim_C060"] = {"diff": p["diff"], "boot95": p["boot95"], "n_questions": p["n_questions"],
                                 "holds": p["boot95"][1] >= 0}
            manifest[f"{key}.diff_answerable_full_code_minus_prompt"] = (p["diff"], p["n_questions"])
            manifest[f"{key}.diff_answerable_full_boot95_lo"] = (p["boot95"][0], p["n_questions"])
            manifest[f"{key}.diff_answerable_full_boot95_hi"] = (p["boot95"][1], p["n_questions"])
        out[key] = res

        lines += ["", f"## {name}", "", f"{res['questions']} questions × 3 repetitions per arm. Full credit, "
                  "jobs with full credit over jobs:", "",
                  "| grading | arm | " + " | ".join(KINDS) + " | answerable (rate, 95% over questions) | "
                  "unanswerable: states a fact |", "|---|---|" + "---|" * len(KINDS) + "---|---|"]
        for grading in ("primary", "secondary"):
            for arm in ARMS:
                e = res["arms"][arm][grading]
                cells = [f"{e['by_kind'][k]['k']}/{e['by_kind'][k]['n']}" if k in e["by_kind"] else "–" for k in KINDS]
                af, sf = e["answerable_full"], e["unanswerable_states_fact"]
                lines.append(f"| {grading} | {arm} | " + " | ".join(cells)
                             + f" | {af['k']}/{af['n']} = {af['rate']} [{af['boot95_questions'][0]}, "
                               f"{af['boot95_questions'][1]}] | {sf['k']}/{sf['n']} |")
        lines += ["", "Paired difference in full credit, code minus prompt (per-question mean of three repetitions; "
                  "bootstrap over questions, 10,000 resamples):", "",
                  "| grading | questions | code | prompt | difference | 95% interval | n | code higher / prompt higher |",
                  "|---|---|---:|---:|---:|---|---:|---|"]
        for grading in ("primary", "secondary"):
            for label, c in res["differences"][grading].items():
                lines.append(f"| {grading} | {label} | {c['code']} | {c['prompt']} | {c['diff']:+.4f} | "
                             f"[{c['boot95'][0]:+.4f}, {c['boot95'][1]:+.4f}] | {c['n_questions']} | "
                             f"{c['questions_code_higher']} / {c['questions_prompt_higher']} |")
        lines += ["", "Jobs and the manipulation check:", "",
                  "| arm | jobs | failed first attempts | failed after one retry | attempts | "
                  "attempts whose system prompt carried the policy | function calls | calls refused in the turn | "
                  "calls the gate did not allow (counted by the harness) | median turn, s |",
                  "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for arm in ARMS:
            e = res["arms"][arm]
            lines.append(f"| {arm} | {e['jobs']} | {e['failed_first_attempts']} | {e['failed_jobs_after_retry']} | "
                         f"{e['attempts']} | {e['attempts_with_policy_in_prompt']}/{e['attempts_with_prompt_seen']} | "
                         f"{e['function_calls']} | {e['calls_denied_in_the_turn']} | "
                         f"{e['calls_gate_did_not_allow']} | {e['wall_s_median']} |")
    (HERE / "data").mkdir(exist_ok=True)
    (HERE / "tables").mkdir(exist_ok=True)
    (HERE / "data" / "metrics.json").write_text(json.dumps(out, indent=2) + "\n")
    with (HERE / "data" / "metrics.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["model", "arm", "grading", "kind", "metric", "k", "n", "value", "lo", "hi"])
        w.writeheader()
        w.writerows(flat)
    (HERE / "tables" / "summary.md").write_text("\n".join(lines) + "\n")
    path = HERE / "manifest.yaml"
    text = path.read_text()
    head, rest = text.split("  values:", 1)
    tail = rest[rest.index("\nbaselines_compared:"):]
    body = "".join(f"\n    {k}: {{mean: {v[0]}, n: {v[1]}}}" for k, v in sorted(manifest.items()))
    path.write_text(head + "  values:" + (body or " {}") + tail)
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
