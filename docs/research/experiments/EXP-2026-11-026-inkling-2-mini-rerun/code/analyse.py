"""EXP-2026-11-026: every number in RESULTS.md, from the collected run files.

Inkling 2 Mini's numbers come from ``data/raw/<source experiment>/`` (copied
there by ``code/collect.sh``); Gemma 4 31B's and Qwen 3.8 27B's — the paper's
— are read from the source experiments' own files, never typed here. A part
whose files are not collected yet is skipped, so this runs after every part.

    python3 docs/research/experiments/EXP-2026-11-026-inkling-2-mini-rerun/code/analyse.py

Writes ``data/metrics.json``, ``data/metrics.csv``, ``tables/part<N>.md`` and
the ``metrics.values`` block of ``manifest.yaml`` (Inkling's numbers, as
``{mean, n}``). Standard library only.
"""

from __future__ import annotations

import csv
import json
import math
import statistics
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
EXPS = HERE.parent
RAW = HERE / "data" / "raw"
INK = "Inkling 2 Mini"
GEMMA = "Gemma 4 31B"
QWEN = "Qwen 3.8 27B"


def wilson(k, n, z=1.96):
    if not n:
        return None
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return [round(max(0.0, c - h), 4), round(min(1.0, c + h), 4)]


MANIFEST: dict = {}


def m(key, k, n):
    """One Inkling number for the manifest: a count k of n, or a value over n runs."""
    MANIFEST[key] = (k, n)


def write_manifest():
    path = HERE / "manifest.yaml"
    text = path.read_text()
    head, rest = text.split("  values:", 1)
    tail = rest[rest.index("\nbaselines_compared:"):]
    body = "".join(f"\n    {k}: {{mean: {v[0]}, n: {v[1]}}}" for k, v in sorted(MANIFEST.items()))
    path.write_text(head + "  values:" + (body or " {}") + tail)


def jsonl(path: Path):
    return [json.loads(x) for x in path.open() if x.strip()]


def frac(k, n):
    return f"{k}/{n}"


# -- part 1: EXP-2026-11-021 model check ---------------------------------------------
def part1(values, tables):
    path = RAW / "EXP-2026-11-021-agent-model-check" / "data" / "metrics.json"
    if not path.exists():
        return
    doc = json.loads(path.read_text())
    rows = {r["tag"]: r for r in doc["rows"]}
    # the paper's "all fixes" rows (Appendix C, Table 4)
    ref = {QWEN: "qwen38-after2-20261117", GEMMA: "gemma4-after2-20261117", INK: "ink"}
    lines = ["<!-- generated by code/analyse.py; do not edit -->", "",
             "| Model | Code | Answered | Leaks / probes | Controls | Full credit / graded | Median s | Worst s |",
             "|---|---|---:|---:|---:|---:|---:|---:|"]
    for model, tag in ref.items():
        r = rows[tag]
        code = "640d7fe0"
        lines.append(f"| {model} | {code} | {frac(r['answered'], r['turns'])} | "
                     f"{frac(r['gate_leaks'], r['gate_probe_turns'])} | "
                     f"{frac(r['controls_passed'], r['controls_run'])} | "
                     f"{frac(r['graded_full'], r['graded'])} | {r['median_s']} | {r['worst_s']} |")
        key = {INK: "ink", GEMMA: "gemma", QWEN: "qwen"}[model]
        for f in ("turns", "answered", "gate_leaks", "gate_probe_turns", "controls_passed",
                  "controls_run", "graded_full", "graded", "median_s", "worst_s"):
            values[f"p1.{key}.{f}"] = r[f]
    g = doc["graded_by_question"]
    lines += ["", "Graded questions not at full credit (recall / precision):", "",
              "| Question | " + " | ".join(ref) + " |", "|---|" + "---|" * len(ref)]
    for q in sorted(g["ink"]):
        cells = [g[t].get(q) for t in ref.values()]
        if all(c and c["full"] for c in cells):
            continue
        lines.append(f"| {q} | " + " | ".join(
            "full" if c and c["full"] else (f"{c['recall']:.2f} / {c['precision']:.2f}" if c else "–")
            for c in cells) + " |")
    r = rows["ink"]
    m("p1_model_check.answered", r["answered"], r["turns"])
    m("p1_model_check.gate_leaks", r["gate_leaks"], r["gate_probe_turns"])
    m("p1_model_check.controls_passed", r["controls_passed"], r["controls_run"])
    m("p1_model_check.full_credit", r["graded_full"], r["graded"])
    m("p1_model_check.median_turn_s", r["median_s"], r["turns"])
    values["p1.ink.missed_recall_below_1"] = sum(1 for c in g["ink"].values() if c["recall"] < 1)
    values["p1.ink.missed_precision_below_1"] = sum(1 for c in g["ink"].values() if c["precision"] < 1)
    tables["part1"] = lines


# -- part 2: EXP-2026-11-010 latency ---------------------------------------------------
def latency(path: Path):
    by = defaultdict(list)
    calls = []
    for r in jsonl(path):
        by[r["group"]].append(r["wall_s"])
        calls += [c.get("seconds") for c in (r.get("model_call_log") or []) if c.get("seconds") is not None]
    out = {g: {"n": len(v), "median_s": round(statistics.median(v), 2), "worst_s": round(max(v), 2)}
           for g, v in by.items()}
    return out


def part2(values, tables):
    base = RAW / "EXP-2026-11-010-agent-loop-cost" / "data"
    if not (base / "a2_inkidle.jsonl").exists():
        return
    src = EXPS / "EXP-2026-11-010-agent-loop-cost" / "data"
    runs = [(f"{QWEN}, idle (A6)", src / "a2_a6idle.jsonl", "qwen.idle"),
            (f"{QWEN}, 8 at once (A6)", src / "a2_a6p8.jsonl", "qwen.p8"),
            (f"{GEMMA}, idle (A5)", src / "a2_a5idle.jsonl", "gemma.idle"),
            (f"{GEMMA}, 8 at once (A5)", src / "a2_a5p8.jsonl", "gemma.p8"),
            (f"{INK}, idle", base / "a2_inkidle.jsonl", "ink.idle"),
            (f"{INK}, 8 at once", base / "a2_inkp8.jsonl", "ink.p8")]
    lines = ["<!-- generated by code/analyse.py; do not edit -->", "",
             "Median (worst) seconds to a complete answer, by question group:", "",
             "| Run | One lookup | A few | Compound | Turns |", "|---|---:|---:|---:|---:|"]
    for label, path, key in runs:
        if not path.exists():
            continue
        t = latency(path)
        cell = lambda g: f"{t[g]['median_s']} ({t[g]['worst_s']})" if g in t else "–"
        lines.append(f"| {label} | {cell('single')} | {cell('few')} | {cell('compound')} | "
                     f"{sum(v['n'] for v in t.values())} |")
        for g, v in t.items():
            for f, x in v.items():
                values[f"p2.{key}.{g}.{f}"] = x
            if key.startswith("ink."):
                m(f"p2_latency.{key[4:]}.{g}.median_s", v["median_s"], v["n"])
                m(f"p2_latency.{key[4:]}.{g}.worst_s", v["worst_s"], v["n"])
    tables["part2"] = lines


def main() -> int:
    values: dict = {}
    tables: dict = {}
    for part in (part1, part2):
        part(values, tables)
    (HERE / "tables").mkdir(exist_ok=True)
    for name, lines in tables.items():
        (HERE / "tables" / f"{name}.md").write_text("\n".join(lines) + "\n")
        print(f"== {name}\n" + "\n".join(lines) + "\n")
    (HERE / "data" / "metrics.json").write_text(json.dumps(values, indent=1, sort_keys=True) + "\n")
    with (HERE / "data" / "metrics.csv").open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["metric", "value"])
        for k in sorted(values):
            w.writerow([k, json.dumps(values[k]) if isinstance(values[k], (list, dict)) else values[k]])
    write_manifest()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
