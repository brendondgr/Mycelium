def wilson(k, n, z=1.96):
    if not n:
        return None
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return [round(max(0.0, c - h), 4), round(min(1.0, c + h), 4)]


MANIFEST: dict = {}


def m(key, k, n):
    """One Inkling number for the manifest: a count k of n, or a value over n runs."""
    MANIFEST[key] = (k, n)


COMPARE: list = []


def cmp(part, group, model, metric, k=None, n=None, value=None):
    """One row of data/compare.csv, the three-model table the figures read."""
    if value is None and k is not None and n:
        value = round(k / n, 4)
    lo, hi = wilson(k, n) if (k is not None and n) else (None, None)
    COMPARE.append({"part": part, "group": group, "model": model, "metric": metric,
                    "k": k, "n": n, "value": value, "lo": lo, "hi": hi})


def write_manifest():
    path = HERE / "manifest.yaml"
    text = path.read_text()
    head, rest = text.split("  values:", 1)
    tail = rest[rest.index("\nbaselines_compared:"):]
    body = "".join(f"\n    {k}: {{mean: {v[0]}, n: {v[1]}}}" for k, v in sorted(MANIFEST.items()))
    path.write_text(head + "  values:" + (body or " {}") + tail)


def jsonl(path: Path):
    return [json.loads(x) for x in path.open() if x.strip()]


def frac(k, n):
    return f"{k}/{n}"


