"""EXP-2026-11-020 Amendment 2: score the person's short calibration sheet
against the 5c reader. Written before any row was marked.

    python3 docs/research/experiments/EXP-2026-11-020-agent-verifier-loop/code/score_details.py

Reads ``data/sheets/calibration_details.csv`` (``judgement``: ``supported``,
``unsupported`` or ``not_a_detail``) and its key. Reports, over marked rows:

* ``not_a_detail`` — rows the person says are not a stated detail (evaluative
  words, the question's own words), by stratum; left out of the rest;
* ``reader_precision`` — of the reader-unsupported rows, the share the person
  also marks unsupported (Wilson 95%);
* ``reader_false_support`` — of the sampled reader-supported rows, the share
  the person marks unsupported (Wilson 95%), and that rate times all
  reader-supported details as an estimate of the unsupported details the
  reader missed;
* ``kappa`` — Cohen's kappa, person against reader, on the rows that are
  details (the strata are equal-sized by design, so kappa is on this sample,
  not on all details).

Writes ``data/metrics_details.json`` and ``tables/calibration_details.md``.
"""

from __future__ import annotations

import csv
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
S = HERE / "data" / "sheets"


def wilson(k: int, n: int, z: float = 1.959964) -> list:
    if not n:
        return [None, None]
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return [round(max(0.0, c - h), 3), round(min(1.0, c + h), 3)]


def main() -> int:
    key = {r["item"]: r for r in csv.DictReader((S / "calibration_details_key.csv").open())}
    person = {r["item"]: r["judgement"].strip().lower() for r in csv.DictReader((S / "calibration_details.csv").open())}
    marked = {i: j for i, j in person.items() if j in ("supported", "unsupported", "not_a_detail")}
    reader_supported_total = int(json.loads((HERE / "data" / "metrics_details_counts.json").read_text())["reader_supported"])
    out = {"items": len(person), "marked": len(marked)}
    for stratum in ("reader_unsupported", "reader_supported_sample"):
        rows = [j for i, j in marked.items() if key[i]["stratum"] == stratum]
        out[stratum] = {"marked": len(rows), "not_a_detail": rows.count("not_a_detail"),
                        "person_unsupported": rows.count("unsupported"), "person_supported": rows.count("supported")}
    fl, sp = out["reader_unsupported"], out["reader_supported_sample"]
    n_fl = fl["person_unsupported"] + fl["person_supported"]
    n_sp = sp["person_unsupported"] + sp["person_supported"]
    out["reader_precision"] = {"k": fl["person_unsupported"], "n": n_fl,
                               "rate": round(fl["person_unsupported"] / n_fl, 4) if n_fl else None,
                               "wilson95": wilson(fl["person_unsupported"], n_fl)}
    fs = sp["person_unsupported"] / n_sp if n_sp else None
    out["reader_false_support"] = {"k": sp["person_unsupported"], "n": n_sp, "rate": round(fs, 4) if fs is not None else None,
                                   "wilson95": wilson(sp["person_unsupported"], n_sp),
                                   "reader_supported_total": reader_supported_total,
                                   "estimated_missed": round(fs * reader_supported_total, 1) if fs is not None else None}
    pairs = [(key[i]["reader_supported"] == "True", j == "supported") for i, j in marked.items() if j != "not_a_detail"]
    n = len(pairs)
    if n:
        agree = sum(a == b for a, b in pairs)
        pr = sum(a for a, _ in pairs) / n
        pp = sum(b for _, b in pairs) / n
        pe = pr * pp + (1 - pr) * (1 - pp)
        out["kappa"] = {"n": n, "agree": agree, "kappa": round((agree / n - pe) / (1 - pe), 4) if pe < 1 else None}
    (HERE / "data" / "metrics_details.json").write_text(json.dumps(out, indent=1) + "\n")
    lines = ["<!-- generated by code/score_details.py; do not edit -->", "",
             "| Stratum | Marked | Not a detail | Person: unsupported | Person: supported |", "|---|---:|---:|---:|---:|",
             f"| reader unsupported | {fl['marked']} | {fl['not_a_detail']} | {fl['person_unsupported']} | {fl['person_supported']} |",
             f"| reader supported (sample) | {sp['marked']} | {sp['not_a_detail']} | {sp['person_unsupported']} | {sp['person_supported']} |", "",
             f"Reader precision (person agrees a flagged detail is unsupported): {out['reader_precision']['k']}/{out['reader_precision']['n']} "
             f"{out['reader_precision']['wilson95']}. Reader false support: {out['reader_false_support']['k']}/{out['reader_false_support']['n']} "
             f"{out['reader_false_support']['wilson95']}; estimated missed unsupported details among {reader_supported_total}: "
             f"{out['reader_false_support']['estimated_missed']}."]
    if n:
        lines.append(f"Cohen's kappa, person against reader, on this sample: {out['kappa']['kappa']} (n = {n}).")
    (HERE / "tables" / "calibration_details.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
