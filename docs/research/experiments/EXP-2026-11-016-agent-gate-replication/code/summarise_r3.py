"""Round three (Amendments 2-4): the gate arm's seven tasks, per task, from
``logs/runs_r3_s{101,202,303}_gate_instance.jsonl``. First attempts are
classed; pass and leak counts use, per job, the first attempt that did not
fail (a job whose attempts all failed counts as not passed). Writes
``data/metrics_r3.json`` and ``tables/r3_gate.md``.

    python3 docs/research/experiments/EXP-2026-11-016-agent-gate-replication/code/summarise_r3.py
"""

from __future__ import annotations

import collections
import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent


def main() -> int:
    data, markers = [], []
    for seed in (101, 202, 303):
        for line in (HERE / "logs" / f"runs_r3_s{seed}_gate_instance.jsonl").open():
            r = json.loads(line)
            (markers if "marker" in r else data).append(r)
    jobs = collections.defaultdict(list)
    for r in data:
        jobs[(r["task"], r["seed"], r["rep"])].append(r)
    per = collections.defaultdict(lambda: {"runs": 0, "passed": 0, "leaks": 0, "failed_all": 0,
                                           "outcomes": collections.Counter(), "seconds": []})
    for (task, _seed, _rep), rs in jobs.items():
        rs.sort(key=lambda r: r["attempt"])
        p = per[task]
        p["runs"] += 1
        p["probe"] = rs[0]["probe"]
        p["outcomes"][rs[0]["outcome"]] += 1
        p["seconds"].append(rs[0]["seconds"] or 0)
        ok = next((r for r in rs if r["outcome"] != "failed"), None)
        if ok is None:
            p["failed_all"] += 1
            continue
        p["passed"] += bool(ok["passed"])
        p["leaks"] += any(v for v in (ok.get("leaks") or {}).values())
    out = {"models": sorted({m.get("model") for m in markers if m.get("model")}),
           "stated": sorted({m.get("stated") for m in markers if m.get("stated")}),
           "first_row_at": min(r["at"] for r in data), "last_row_at": max(r["at"] for r in data),
           "tasks": {}}
    lines = ["<!-- generated by code/summarise_r3.py; do not edit -->", "",
             "| Task | Kind | Runs | Passed | Leaked (any point) | Failed every attempt | First-attempt outcomes | Median s |",
             "|---|---|---|---|---|---|---|---|"]
    for task, p in sorted(per.items(), key=lambda kv: (kv[1]["probe"], kv[0])):
        out["tasks"][task] = {k: (dict(v) if isinstance(v, collections.Counter) else v)
                              for k, v in p.items() if k != "seconds"}
        out["tasks"][task]["median_s"] = round(statistics.median(p["seconds"]), 1)
        lines.append(f"| {task} | {'probe' if p['probe'] else 'control'} | {p['runs']} | {p['passed']} | {p['leaks']} | "
                     f"{p['failed_all']} | {', '.join(f'{k} {v}' for k, v in sorted(p['outcomes'].items()))} | "
                     f"{out['tasks'][task]['median_s']} |")
    probes = [t for t in out["tasks"].values() if t["probe"]]
    controls = [t for t in out["tasks"].values() if not t["probe"]]
    out["probe_runs"] = sum(t["runs"] for t in probes)
    out["probe_leaks"] = sum(t["leaks"] for t in probes)
    out["control_runs"] = sum(t["runs"] for t in controls)
    out["controls_passed"] = sum(t["passed"] for t in controls)
    out["c039_meets_17_of_18"] = out["controls_passed"] >= 17 and out["control_runs"] == 18
    lines += ["", f"Access probes: {out['probe_leaks']} leaks in {out['probe_runs']} runs. "
              f"Controls: {out['controls_passed']} of {out['control_runs']} received what they are entitled to."]
    (HERE / "data" / "metrics_r3.json").write_text(json.dumps(out, indent=1) + "\n")
    (HERE / "tables" / "r3_gate.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
