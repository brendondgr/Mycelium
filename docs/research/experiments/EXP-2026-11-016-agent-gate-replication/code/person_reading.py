"""The person's reading of the adjudication sheet (round three, Phase 5),
by stratum, beside the string grader (the stratum) and the model reader.
Writes ``tables/adjudication_person.md``; agreement (kappa) is computed by
``analyse.py`` into ``data/metrics.json``.

    python3 docs/research/experiments/EXP-2026-11-016-agent-gate-replication/code/person_reading.py
"""

import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
S = HERE / "data" / "sheets"
key = {r["row"]: r for r in csv.DictReader((S / "adjudication_key.csv").open())}
model = {r["row"]: r["revealed_secret"].strip().lower() for r in csv.DictReader((S / "adjudication_model.csv").open())}
person = {r["row"]: r["revealed_secret"].strip().lower() for r in csv.DictReader((S / "adjudication.csv").open())}
agree = json.loads((HERE / "data" / "metrics.json").read_text())["adjudication"]["agreement"]
lines = ["<!-- generated by code/person_reading.py; do not edit -->", "",
         "| Stratum (string grader) | Rows | Person: revealed | Model reader: revealed | Person and model agree |",
         "|---|---:|---:|---:|---:|"]
for stratum in sorted({k["stratum"] for k in key.values()}):
    rows = [r for r in person if key[r]["stratum"] == stratum]
    lines.append(f"| {stratum} | {len(rows)} | {sum(person[r] == 'yes' for r in rows)} | "
                 f"{sum(model[r] == 'yes' for r in rows)} | {sum(person[r] == model[r] for r in rows)} |")
lines += ["", "Rows where the person and the string grader differ: "
          + ", ".join(f"{r} ({key[r]['task']}, person {person[r]})" for r in sorted(person, key=int)
                      if (person[r] == "yes") != (key[r]["stratum"].endswith("leak"))) + ".",
          "", "Cohen's kappa (from `data/metrics.json`): string–person " f"{agree['string_vs_person']['kappa']}, "
          f"model–person {agree['model_vs_person']['kappa']}, string–model {agree['string_vs_model']['kappa']} (n = 20)."]
(HERE / "tables" / "adjudication_person.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
