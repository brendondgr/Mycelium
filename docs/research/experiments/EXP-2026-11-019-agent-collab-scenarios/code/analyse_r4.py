"""EXP-2026-11-019 Amendment 7: ``analyse_r3.py`` unchanged on a tagged run's
logs (default ``r4``, Gemma 4 31B), plus the count the amendment registered:
how many empty model calls fit the lead from EXP-2026-11-010 arm A6.

    python3 docs/research/experiments/EXP-2026-11-019-agent-collab-scenarios/code/analyse_r4.py [tag]

``analyse_r3.py`` reads ``logs/runs_r3_<mode>_instance_r3.jsonl`` and
EXP-2026-11-016's gate rows by fixed paths. This stages the tagged logs under
those names in a temporary folder with no EXP-2026-11-016 rows (not run for
this tag), points the script at it, and copies its outputs back as
``data/metrics_<tag>.json``, ``tables/<tag>_outcomes.md`` and
``tables/empty_turns_<tag>.md``. Then it writes ``tables/<tag>_empty_causes.md``
and adds ``empty_causes`` to the metrics file. Standard library only.

An empty call (no text, no function call) is put in exactly one row, first
match: a server error or cut-off (an exception, or ``finish_reason`` length);
a call the parser dropped (call markup in the reasoning or the content);
reasoning with no reply (reasoning text, no markup); nothing at all (no
reasoning either). Beside it: whether it *fits the lead* — made with
functions disallowed (``tool_choice == "none"``) and still spent completion
tokens — and whether the turn's recall was non-empty.
"""

from __future__ import annotations

import collections
import json
import shutil
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import analyse_r3 as A  # noqa: E402


def cause(c: dict) -> str:
    if c.get("exception") or c.get("finish_reason") == "length":
        return "server error or cut-off"
    if c.get("markup_in_reasoning") or c.get("markup_in_content"):
        return "a call the parser dropped"
    if (c.get("reasoning_chars") or 0) > 0:
        return "reasoning, no reply"
    return "nothing at all"


def main() -> int:
    tag = sys.argv[1] if len(sys.argv) > 1 else "r4"
    stage = Path(tempfile.mkdtemp())
    for d in ("logs", "data", "tables"):
        (stage / d).mkdir()
    logs = {}
    for mode in ("repeated", "fresh"):
        src = HERE / "logs" / f"runs_r3_{mode}_instance_{tag}.jsonl"
        if not src.exists():
            print("missing", src.name)
            return 1
        logs[mode] = src
        shutil.copy(src, stage / "logs" / f"runs_r3_{mode}_instance_r3.jsonl")
    A.HERE, A.E16 = stage, stage / "no-016-rows"
    A.main()
    shutil.copy(stage / "tables" / "r3_outcomes.md", HERE / "tables" / f"{tag}_outcomes.md")
    shutil.copy(stage / "tables" / "empty_turns.md", HERE / "tables" / f"empty_turns_{tag}.md")
    out = json.loads((stage / "data" / "metrics_r3.json").read_text())

    rows = collections.Counter()
    calls = empties = fit = 0
    by_choice = collections.Counter()
    turns_with_empty = collections.Counter()
    for mode, path in logs.items():
        for line in path.open():
            r = json.loads(line)
            if "marker" in r:
                continue
            log = r.get("model_call_log") or []
            calls += len(log)
            had = False
            for c in log:
                if not c.get("empty"):
                    continue
                had = True
                empties += 1
                lead = c.get("tool_choice") == "none" and (c.get("completion_tokens") or 0) > 0
                fit += bool(lead)
                by_choice[str(c.get("tool_choice"))] += 1
                rows[(mode, cause(c), bool(lead), bool(r.get("recall_nonempty")))] += 1
            if had:
                turns_with_empty[(mode, r["outcome"])] += 1
    causes = collections.Counter()
    for (mode, why, lead, recall), n in rows.items():
        causes[why] += n
    out["empty_causes"] = {
        "tag": tag, "model_calls": calls, "empty_calls": empties,
        "fit_the_lead": fit, "by_tool_choice": dict(by_choice), "by_cause": dict(causes),
        "largest_cause_share": round(max(causes.values()) / empties, 4) if empties else None,
        "rows": [{"mode": m, "cause": w, "fits_lead": lead, "recall_nonempty": rc, "n": n}
                 for (m, w, lead, rc), n in sorted(rows.items(), key=lambda kv: -kv[1])],
        "turns_with_an_empty_call": [{"mode": m, "outcome": o, "n": n}
                                     for (m, o), n in sorted(turns_with_empty.items())],
    }
    (HERE / "data" / f"metrics_{tag}.json").write_text(json.dumps(out, indent=1, default=str) + "\n")
    md = [f"<!-- generated by code/analyse_r4.py {tag}; do not edit -->", "",
          f"Empty model calls: {empties} of {calls}. Fit the lead (functions disallowed, completion tokens spent): "
          f"{fit} of {empties}.", "",
          "| Mode | Cause (first match) | Fits the lead | Recall non-empty | Empty calls |", "|---|---|---|---|---|"]
    md += [f"| {m} | {w} | {'yes' if lead else 'no'} | {'yes' if rc else 'no'} | {n} |"
           for (m, w, lead, rc), n in sorted(rows.items(), key=lambda kv: -kv[1])]
    md += ["", "| Mode | Outcome of a turn that had an empty call | Turns |", "|---|---|---|"]
    md += [f"| {m} | {o} | {n} |" for (m, o), n in sorted(turns_with_empty.items())]
    (HERE / "tables" / f"{tag}_empty_causes.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
